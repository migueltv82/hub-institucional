export const INSTITUTIONAL_SUBJECT_AFFINITIES = new Map()

GROUPS.split('\n').forEach((line) => {
  const [grupoAfinMesa, codesText] = line.split(':')
  const codes = codesText.split(',')
  codes.forEach((code) => INSTITUTIONAL_SUBJECT_AFFINITIES.set(code, {
    grupoAfinMesa,
    codigosMateriasAfines: codes.filter((candidate) => candidate !== code),
  }))
})

export function getInstitutionalSubjectAffinity(code) {
  return INSTITUTIONAL_SUBJECT_AFFINITIES.get(String(code ?? '').trim().toUpperCase()) ?? null
}
